/**
 * 根据武将ID获取武将名称
 * @param {number|string} heroId 武将ID
 * @returns {string} 武将名称，未知返回"武将"+ID
 */
function getHeroName(heroId) {
  if (!heroId || heroId === 0) return ''
  const id = parseInt(heroId)
  
  // 兼容 > 130000 的动态/典藏皮肤 ID
  let baseId = id
  if (id > 130000) {
    baseId = id - 30000
  }

  // 从官方配置 JSON 查找
  if (herocfg[baseId] && herocfg[baseId].name) {
    return herocfg[baseId].name
  }

  // 兜底：先直接查找
  if (heroMap[baseId]) return heroMap[baseId]
  
  // 兜底：尝试通过 iconId 映射查找
  if (iconIdMap[baseId]) {
    const realBaseId = iconIdMap[baseId]
    if (heroMap[realBaseId]) return heroMap[realBaseId]
  }
  return `武将${id}`
}

/**
 * 根据武将ID获取头像 iconId
 * @param {number|string} heroId 武将ID
 * @returns {number|string} 图标ID
 */
function getHeroIconId(heroId) {
  if (!heroId || heroId === 0) return 0
  const id = parseInt(heroId)
  
  // 从官方配置 JSON 查找 iconId
  if (herocfg[id] && herocfg[id].iconId) {
    return herocfg[id].iconId
  }

  let baseId = id
  if (id > 130000) {
    baseId = id - 30000
  }
  
  if (herocfg[baseId] && herocfg[baseId].iconId) {
    return herocfg[baseId].iconId
  }
  
  if (iconIdMap[baseId]) {
    return iconIdMap[baseId]
  }
  return baseId
}

/**
 * 格式化武将列表显示
 * @param {number|string} hero1Id 武将1ID
 * @param {number|string} hero2Id 武将2ID
 * @param {number|string} hero3Id 武将3ID
 * @returns {Array} 包含名称和ID的武将数组
 */
function formatHeroList(hero1Id, hero2Id, hero3Id) {
  return [
    { id: hero1Id, name: getHeroName(hero1Id), iconId: getHeroIconId(hero1Id) },
    { id: hero2Id, name: getHeroName(hero2Id), iconId: getHeroIconId(hero2Id) },
    { id: hero3Id, name: getHeroName(hero3Id), iconId: getHeroIconId(hero3Id) }
  ].filter(h => h.id && h.id !== 0)
}

/**
 * 根据战法ID获取战法名称
 * @param {number|string} skillId 战法ID
 * @returns {string} 战法名称，未知返回"未知"
 */
function getSkillName(skillId) {
  if (!skillId || skillId === 0 || skillId === '0') return ''
  const id = parseInt(skillId)
  if (skillcfg[id] && skillcfg[id].name) {
    return skillcfg[id].name
  }
  return '未知'
}

/**
 * 解析所有战法信息
 * @param {string} allSkillInfo 原始战法信息字符串
 * @returns {Array} 解析后的战法数组
 */
function parseSkillInfo(allSkillInfo) {
  if (!allSkillInfo) return []
  
  let all_skill_info_arr = allSkillInfo.split(';').filter(item => item !== '')
  let all_skill_info = []
  
  all_skill_info_arr.forEach(e => {
    let obj = {}
    let arr = e.split(',')
    obj.index = arr[0]
    obj.skill1id = arr[1]
    obj.skill1level = arr[2]
    obj.skill2id = arr[3]
    obj.skill2level = arr[4]
    obj.skill3id = arr[5]
    obj.skill3level = arr[6]
    
    // 获取战法名称
    obj.skill1Name = getSkillName(obj.skill1id)
    obj.skill2Name = getSkillName(obj.skill2id)
    obj.skill3Name = getSkillName(obj.skill3id)
    
    all_skill_info.push(obj)
  })
  
  return all_skill_info
}

